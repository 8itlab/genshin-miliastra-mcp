// This fixture tests binary replacement and transactions only. It is NOT a playable map.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { buildFile, encodeVarint } from 'genshin-ts/injector/binary';
import { loadGiaProto } from 'genshin-ts/injector/proto';
import { ROOT, Service, runNode } from '../src/core.mjs';
import { inspectBytes, sha } from '../src/adapter.mjs';
const field=(id,b)=>Buffer.concat([Buffer.from(encodeVarint(id*8+2)),Buffer.from(encodeVarint(b.length)),b]);
const {nodeGraphMessage}=loadGiaProto();
const graph=Buffer.from(nodeGraphMessage.encode({id:{class:10000,type:20000,kind:21001,id:1073741825},name:'_GSTS_MCP_Test'}).finish());
const payload=Buffer.concat([field(10,field(1,field(1,graph))),field(1000,Buffer.from('unknown-field-preserved'))]);
const bytes=buildFile(payload,{schema:1,headTag:0x326,fileType:2,tailTag:0x679});
assert.equal(inspectBytes(bytes).graphs.length,1);
const fixtureRoot=path.join(ROOT,'workspace','fixtures-'+Date.now()),mapDir=path.join(fixtureRoot,'1','Beyond_Local_Save_Level');
fs.mkdirSync(mapDir,{recursive:true});fs.writeFileSync(path.join(mapDir,'1073741825.gil'),bytes);
const service=new Service();
assert.throws(()=>service.project('../escape'),e=>e.code==='INVALID_PROJECT_ID');
assert.throws(()=>inspectBytes(Buffer.alloc(30)),e=>e.code==='INVALID_GIL');
process.env.MILIASTRA_SAVE_ROOTS=JSON.stringify([fixtureRoot]);process.env.MILIASTRA_SYNTHETIC='1';
process.env.MILIASTRA_TEST_MAP=path.join(mapDir,'1073741825.gil');process.env.MILIASTRA_TEST_SHA256=sha(bytes);
const result=await runNode([path.join(ROOT,'tests','mcp-smoke.mjs')],ROOT);
console.log(result.output);assert.equal(result.exitCode,0);
const report=JSON.parse(fs.readFileSync(path.join(ROOT,'workspace','synthetic-smoke-report.json'),'utf8'));
const working=fs.readFileSync(path.join(report.workspace,report.projectId,'working.gil'));
assert.deepEqual(working,bytes,'Rollback must restore every original byte, including unknown fields');
const apply=report.transcript.find(r=>r.tool==='apply_build'&&!r.isError).result;
const undo=report.transcript.find(r=>r.tool==='restore_backup').result.undoBackupId;
const applied=fs.readFileSync(path.join(report.workspace,report.projectId,'backups',undo+'.gil'));
assert.ok(applied.includes(Buffer.from('unknown-field-preserved')),'Unknown protobuf field must survive injection');
assert.ok(inspectBytes(applied).graphs[0].nodeCount>=2);
assert.notEqual(apply.beforeSha256,apply.afterSha256);
console.log('PASS: synthetic binary injection, unknown-field preservation, conflict rejection and byte-exact rollback. No in-game claims.');
